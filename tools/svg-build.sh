#!/bin/bash
# Build the game's vector assets from templates and design tokens.
#
#   bash tools/svg-build.sh            build every game/assets/_src/**/*.svg.tpl
#   bash tools/svg-build.sh glass      only templates whose path contains "glass"
#
# A template is an SVG whose colours and sizes are {{token}} names from
# game/assets/_style/tokens.json. Each one becomes game/assets/<same path>.svg
# (Godot imports SVG directly), is checked with tools/svg-check.sh and is
# recorded in game/assets/ASSETS.md (source "claude-vector", cost 0).
# Change a colour in tokens.json, run this again: every asset follows.
set -u
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/../.claude/hooks/lib.sh"
cd "$ROOT" || exit 2

TOKENS=game/assets/_style/tokens.json
SRC=game/assets/_src
filter="${1:-}"
[ -f "$TOKENS" ] || { echo "svg-build: $TOKENS missing (run /art-style)"; exit 2; }
[ -d "$SRC" ] || { echo "svg-build: no templates in $SRC"; exit 0; }
[ -f "$SRC/.gdignore" ] || : > "$SRC/.gdignore"

# tokens.json -> "key<TAB>value" lines (flat object of strings/numbers).
tmp="$(mktemp -d 2>/dev/null || mktemp -d -t svgb)"
if [ -z "${GSL_NO_JQ:-}" ] && command -v jq >/dev/null 2>&1; then
  jq -r 'to_entries[] | select(.key | test("^[a-z0-9_]+$")) | "\(.key)\t\(.value)"' "$TOKENS" > "$tmp/tokens.tsv" || { echo "svg-build: $TOKENS is not valid JSON"; exit 2; }
else
  grep -oE '"[a-z0-9_]+"[[:space:]]*:[[:space:]]*("[^"]*"|-?[0-9.]+)' "$TOKENS" \
    | sed -E 's/^"([a-z0-9_]+)"[[:space:]]*:[[:space:]]*"?([^"]*)"?$/\1\t\2/' > "$tmp/tokens.tsv"
fi

# Colour tokens for code: game/scripts/generated/design_tokens.gd, so game
# code (liquid colours, UI) uses exactly the same values as the SVGs.
mkdir -p game/scripts/generated
{
  echo "class_name DesignTokens"
  echo "## Generated by tools/svg-build.sh from game/assets/_style/tokens.json. Do not edit:"
  echo "## change tokens.json and run the build again."
  echo ""
  echo "const COLORS := {"
  awk -F'\t' 'tolower($2) ~ /^#[0-9a-f]{6}$/ {
      h = tolower(substr($2, 2)); split("0123456789abcdef", d, "")
      for (i = 1; i <= 16; i++) v[d[i]] = i - 1
      r = (v[substr(h,1,1)] * 16 + v[substr(h,2,1)]) / 255
      g = (v[substr(h,3,1)] * 16 + v[substr(h,4,1)]) / 255
      b = (v[substr(h,5,1)] * 16 + v[substr(h,6,1)]) / 255
      printf "\t&\"%s\": Color(%.4f, %.4f, %.4f),\n", $1, r, g, b
    }' "$tmp/tokens.tsv"
  echo "}"
  echo ""
  echo ""
  echo "static func color(token: StringName) -> Color:"
  echo "	return COLORS.get(token, Color.MAGENTA)"
} > game/scripts/generated/design_tokens.gd

built=0; failed=0
while IFS= read -r tpl; do
  rel="${tpl#"$SRC"/}"; rel="${rel%.tpl}"
  [ -n "$filter" ] && case "$rel" in *"$filter"*) ;; *) continue ;; esac
  out="$tmp/out.svg"
  awk -F'\t' -v miss="$tmp/missing" 'NR == FNR { tok[$1] = $2; next }
    {
      line = $0; res = ""
      while (match(line, /\{\{[a-z0-9_]+\}\}/)) {
        k = substr(line, RSTART + 2, RLENGTH - 4)
        if (k in tok) v = tok[k]; else { v = "MISSING_" k; print k >> miss }
        res = res substr(line, 1, RSTART - 1) v; line = substr(line, RSTART + RLENGTH)
      }
      print res line
    }' "$tmp/tokens.tsv" "$tpl" > "$out"
  if [ -s "$tmp/missing" ]; then
    echo "svg-build: $rel: unknown tokens: $(sort -u "$tmp/missing" | tr '\n' ' ')"; rm -f "$tmp/missing"; failed=$((failed+1)); continue
  fi
  if ! chk="$(bash tools/svg-check.sh "$out" 2>&1)"; then
    echo "svg-build: $rel failed svg-check:"; printf '%s\n' "$chk" | grep ERROR | sed "s#$out#$rel#"; failed=$((failed+1)); continue
  fi
  bash tools/import-asset.sh "$out" "$rel" --no-raw --model claude-vector --cost 0 --note "built from _src/$rel.tpl" >/dev/null || { failed=$((failed+1)); continue; }
  built=$((built+1))
done < <(find "$SRC" -type f -name '*.svg.tpl' | sort)
rm -rf "$tmp"
echo "svg-build: $built built, $failed failed"
[ "$failed" -eq 0 ]
